export const getRuneIconUrl = (runeId) => {
  if (!runeId) return null;
  const iconPath = RUNE_MAP[runeId];
  if (!iconPath) return null;
  return `https://ddragon.leagueoflegends.com/cdn/img/${iconPath}`;
};

export const getStatShardIconUrl = (shardId) => {
  if (!shardId) return null;
  const iconPath = STAT_SHARD_MAP[shardId];
  if (!iconPath) return null;
  return `https://ddragon.leagueoflegends.com/cdn/img/${iconPath}`;
};

export const getStyleIconUrl = (styleId) => {
  if (!styleId) return null;
  const icon = STYLE_MAP[styleId];
  return icon ? `https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/default/v1/perk-images/styles/${icon}.png` : null;
};
